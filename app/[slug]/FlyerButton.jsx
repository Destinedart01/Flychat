'use client';

export default function FlyerButton({ slug, countryCode, phone, message }) {
  function handleClick() {
    fetch('/api/track-click', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ slug }),
    }).catch(() => {});

    const digits = (countryCode + phone).replace(/[^0-9]/g, '');
    const text = message ? `?text=${encodeURIComponent(message)}` : '';
    window.location.href = `https://wa.me/${digits}${text}`;
  }

  return (
    <button onClick={handleClick} className="btn btn-wa">
      <WhatsAppIcon />
      Chat on WhatsApp
    </button>
  );
}

